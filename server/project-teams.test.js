import test from 'node:test';
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { migrateProjectTeams } from './project-teams.js';
import { TRACKS, buildBoards } from './rules.js';

test('legacy migration preserves project averages, source data and snapshots; idempotent per date', () => {
  const db=new DatabaseSync(':memory:');
  db.exec(`PRAGMA foreign_keys=ON;
    CREATE TABLE teams(id TEXT PRIMARY KEY,name TEXT,slogan TEXT,color TEXT,captain_id TEXT,demo INTEGER,created INTEGER);
    CREATE TABLE users(id TEXT PRIMARY KEY,name TEXT,team_id TEXT REFERENCES teams(id),created INTEGER);
    CREATE TABLE enrollments_v2(user_id TEXT,date TEXT,track TEXT,created INTEGER,PRIMARY KEY(user_id,date,track));
    CREATE TABLE entries_v2(user_id TEXT,date TEXT,track TEXT,value REAL,morning REAL,evening REAL,updated INTEGER);
    CREATE TABLE reports_v2(payload TEXT);
    INSERT INTO teams VALUES ('old','老队','口号','sage','a',0,1),('empty','空队','','sage','d',0,2);
    INSERT INTO users VALUES ('a','甲','old',1),('b','乙','old',2),('c','丙','old',3),('d','丁','empty',4);
    INSERT INTO enrollments_v2 VALUES ('a','2026-11-01','steps',1),('b','2026-11-01','steps',2),('b','2026-11-01','water',2),('c','2026-11-01','loss',3);
    INSERT INTO entries_v2 VALUES ('a','2026-11-01','steps',8000,NULL,NULL,1),('b','2026-11-01','water',3,NULL,NULL,2),('c','2026-11-01','loss',NULL,120,122,3);
    INSERT INTO reports_v2 VALUES ('{"frozen":"original snapshot"}');
  `);
  const original=()=>JSON.stringify(['teams','users','enrollments_v2','entries_v2','reports_v2'].map(t=>db.prepare(`SELECT * FROM ${t}`).all()));
  const before=original();
  migrateProjectTeams(db,'2026-11-01',TRACKS);
  const teams=db.prepare('SELECT * FROM project_teams_v4').all();
  assert.equal(teams.length,3); assert.ok(teams.every(t=>t.legacy_id==='old'));
  assert.equal(teams.find(t=>t.track==='water').captain_id,'b');
  const memberships=db.prepare('SELECT * FROM team_members_v4').all();
  const users=db.prepare('SELECT * FROM users').all().map(u=>({...u,team_ids:Object.fromEntries(memberships.filter(m=>m.user_id===u.id).map(m=>[m.track,m.team_id]))}));
  const boards=buildBoards(users,teams,db.prepare('SELECT * FROM enrollments_v2').all(),db.prepare('SELECT * FROM entries_v2').all());
  assert.equal(boards.steps.team[0].score,4000); assert.equal(boards.steps.team[0].count,2);
  assert.equal(boards.water.team[0].score,3); assert.equal(boards.water.team[0].count,1);
  assert.equal(boards.loss.team[0].score,2); assert.equal(boards.loss.team[0].count,1);
  assert.equal(boards.gain.team.length,0);
  assert.equal(original(),before);
  migrateProjectTeams(db,'2026-11-01',TRACKS);
  assert.deepEqual(db.prepare('SELECT * FROM project_teams_v4').all(),teams);
  assert.deepEqual(db.prepare('SELECT * FROM team_members_v4').all(),memberships);
  assert.throws(()=>db.prepare('INSERT INTO team_members_v4 VALUES (?,?,?,?,?)').run(teams[0].id,'d','2026-11-01','water',5));
  migrateProjectTeams(db,'2026-11-02',TRACKS);
  assert.equal(db.prepare('SELECT count(*) n FROM project_teams_v4').get().n,3);
  assert.equal(original(),before);
  db.close();
});
